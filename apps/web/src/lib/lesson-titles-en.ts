/** Ders başlığı dile göre (anahtarla). İngilizcesi yoksa Türkçe kalır. */
export const lessonTitleByKey = (key: string, trTitle: string, locale: Locale): string =>
  (locale === 'en' && LESSON_TITLES_EN[key]) || trTitle

/** Ders başlığı dile göre (modül slug'ı + hafta sırası + ders sırası). */
export const lessonTitle = (moduleSlug: string, weekPos: number, lessonPos: number, trTitle: string, locale: Locale): string =>
  lessonTitleByKey(lessonKey(moduleSlug, weekPos, lessonPos), trTitle, locale)
