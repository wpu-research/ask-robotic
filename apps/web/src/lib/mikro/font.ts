const FOLD: Record<string, string> = { Ç: 'C', Ğ: 'G', İ: 'I', I: 'I', Ö: 'O', Ş: 'S', Ü: 'U', ı: 'I' }

export function glyphOf(ch: string): string[] {
  const up = FOLD[ch] ?? ch.toLocaleUpperCase('tr')
  const folded = FOLD[up] ?? up
  return G[folded] ?? G['?']
}

/** Metni, her biri 5 bitlik (bit i = i. satır) sütun dizisine çevirir; harfler arasında 1 boş sütun vardır. */
export function textColumns(text: string): number[] {
  const cols: number[] = []
  const chars = [...text]
  chars.forEach((ch, i) => {
    const g = glyphOf(ch)
    const w = g[0].length
    for (let x = 0; x < w; x++) {
      let v = 0
      for (let y = 0; y < 5; y++) if (g[y][x] === '#') v |= 1 << y
      cols.push(v)
    }
    if (i < chars.length - 1) cols.push(0)
  })
  return cols
}

export const SCROLL_COL_MS = 90

/** Kaydırmalı yazının toplam süresi (ms). */
export function scrollDuration(text: string): number {
  return (textColumns(text).length + 5) * SCROLL_COL_MS
}

/** Kaydırmanın `elapsed` ms sonraki karesi (25 elemanlı, satır sıralı, 0/255). */
export function scrollFrame(text: string, elapsed: number): Uint8Array {
  const cols = textColumns(text)
  const k = Math.floor(Math.max(0, elapsed) / SCROLL_COL_MS) + 1
  const out = new Uint8Array(25)
  for (let x = 0; x < 5; x++) {
    const ci = k - 5 + x
    const v = ci >= 0 && ci < cols.length ? cols[ci] : 0
    for (let y = 0; y < 5; y++) if (v & (1 << y)) out[y * 5 + x] = 255
  }
  return out
}

/** Tek glif (örn. tek rakam) ortalanmış 25 elemanlı kare. */
export function glyphFrame(ch: string): Uint8Array {
  const g = glyphOf(ch)
  const w = g[0].length
  const off = Math.floor((5 - w) / 2)
  const out = new Uint8Array(25)
  for (let y = 0; y < 5; y++) for (let x = 0; x < w; x++) if (g[y][x] === '#') out[y * 5 + x + off] = 255
  return out
}
